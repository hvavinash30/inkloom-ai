"""Workspace-grounded assistant.

This build does not call an external language model. The assistant is a
deterministic guide over the workspace's actual records: approved facts,
brand rules, audits, findings, reviews, and campaigns. Every answer declares
how it was produced and what it was grounded in. When the records do not
contain an answer, it says so instead of guessing.
"""
