STOP_WORDS = {
    "what", "which", "where", "when", "who", "how", "does", "do", "is", "are",
    "the", "our", "we", "i", "my", "can", "should", "for", "about", "with",
    "say", "says", "tell", "me", "of", "on", "in", "to", "a", "an", "and",
    "it", "this", "that", "please", "current", "approved", "fact", "facts",
}


def _keywords(message: str) -> list[str]:
    words = re.findall(r"[a-z0-9]+", message.lower())
    return [w for w in words if len(w) > 2 and w not in STOP_WORDS]


def _focused_document(db: Session, actor: Actor, document_id: str) -> ContentDocument:
    document = db.query(ContentDocument).filter(ContentDocument.id == document_id).first()
    if not document:
        raise HTTPException(status_code=404, detail="The referenced content was not found.")
    if not actor.can_access_document(document):
        raise HTTPException(status_code=403, detail="You do not have access to this content.")
    return document


def _accessible_documents(db: Session, actor: Actor) -> list[ContentDocument]:
    query = db.query(ContentDocument).filter(ContentDocument.workspace_id == actor.workspace_id)
    if not actor.can("content.read.all"):
        query = query.filter(ContentDocument.created_by == actor.id)
    return query.all()


def _latest_audit(db: Session, document: ContentDocument):
    version = content_service.latest_version(db, document.id)
    if not version:
        return version, None
    return version, content_service.latest_audit_for_version(db, version.id)


def _base_actions(document: Optional[ContentDocument]) -> list[AssistantActionSuggestion]:
    if not document:
        return []
    return [
        AssistantActionSuggestion(
            action_type="open_document",
            label=f"Open “{document.title}”",
            route=f"/content/{document.id}",
            target_id=document.id,
        )
    ]


def _assistant_engine_note() -> str:
    if settings.llm_configured:
        return (
            "A language model is configured server-side. It may rephrase a record-grounded answer, but "
            "every fact comes from stored workspace records."
        )
    return (
        "No external language model is configured in this deployment. Answers come from the built-in "
        "grounded guide over workspace records and are not generated by an LLM."
    )


def _result(
    *,
    reply: str,
    verification: str,
    verification_note: str,
    grounding: Optional[list[AssistantGroundingItem]] = None,
    actions: Optional[list[AssistantActionSuggestion]] = None,
    limitations: Optional[list[str]] = None,
) -> AssistantChatResponse:
    return AssistantChatResponse(
        reply=reply,
        mode="rule_based",
        verification=verification,
        verification_note=verification_note,
        grounding=grounding or [],
        suggested_actions=actions or [],
        limitations=limitations or [
            "The assistant reads workspace records only; it does not have internet access.",
            "It is read-only: it can suggest corrections and open pages, but it never approves, publishes, edits, or deletes content.",
            _assistant_engine_note(),
        ],
        diagnostic_info={"engine": "workspace-grounded-guide-v1"},
    )


def _finding_line(finding: AuditFinding) -> str:
    location = finding.location_label or (
        f"Page {finding.page_number}" if finding.page_number else "Document"
    )
    correction = (
        f" Suggested correction: “{finding.suggested_correction}”."
        if finding.suggested_correction
        else " No automatic correction is available; a human should decide."
    )
    return (
        f"• [{finding.severity.upper()}] “{finding.affected_text}” at {location} — "
        f"{finding.title}.{correction}"
    )


def _answer_for_document(
    db: Session, actor: Actor, document: ContentDocument, message: str
) -> AssistantChatResponse:
    version, run = _latest_audit(db, document)
    lowered = message.lower()
    grounding: list[AssistantGroundingItem] = [
        AssistantGroundingItem(
            kind="record",
            title=document.title,
            detail=(
                f"{document.asset_type.upper()} · {document.content_type.replace('_', ' ')} · "
                f"status {document.status.replace('_', ' ')} · version "
                f"{document.current_version_number}"
            ),
        )
    ]
    if run:
        grounding.append(
            AssistantGroundingItem(
                kind="audit_finding",
                title=f"Latest check · readiness {run.overall_score}/100",
                detail=(
                    f"{run.total_findings} finding(s), risk level {run.risk_level}, "
                    f"verification {run.verification_status.replace('_', ' ')}."
                ),
                source_reference=f"Audit run {run.id[:8]}",
            )
        )

    if not version:
        return _result(
            reply=(
                f"“{document.title}” does not have a saved version yet, so there is nothing to audit. "
                "Add the content and run a check first."
            ),
            verification="verified_from_workspace_records",
            verification_note="Document metadata was read from the workspace database.",
            grounding=grounding,
            actions=_base_actions(document),
        )

    if not run:
        return _result(
            reply=(
                f"“{document.title}” is saved as version {version.version_number}, but it has not been "
                "checked yet. Run a check to produce evidence-linked findings."
            ),
            verification="verified_from_workspace_records",
            verification_note="The assistant confirmed that no audit run exists for the current version.",
            grounding=grounding,
            actions=_base_actions(document),
        )

    findings = (
        db.query(AuditFinding)
        .filter(AuditFinding.audit_run_id == run.id, AuditFinding.status == "open")
        .order_by(AuditFinding.page_number, AuditFinding.timestamp_seconds, AuditFinding.created_at)
        .all()
    )

    if findings and re.search(r"\b(fix|fixes|correct|correction|corrections|revise|revision|rewrite|change)\b", lowered):
        corrections = [finding for finding in findings if finding.suggested_correction][:4]
        if corrections:
            reply = (
                f"Suggested corrections for “{document.title}” based on stored findings. "
                "These are suggestions only; the original content has not been changed.\n\n"
                + "\n".join(
                    f"• At {finding.location_label or (f'page {finding.page_number}' if finding.page_number else 'the document')}: "
                    f"“{finding.affected_text}” → “{finding.suggested_correction}” "
                    f"({finding.title}, {finding.severity})."
                    for finding in corrections
                )
            )
        else:
            reply = (
                f"The stored findings for “{document.title}” do not include an automatic correction. "
                "Open the content item to review each finding's evidence and decide the revision. "
                "The assistant will not rewrite or save the document on its own."
            )
        return _result(
            reply=reply,
            verification="verified_from_workspace_records",
            verification_note=(
                "Corrections are quoted from stored findings. Nothing was applied to the document."
            ),
            grounding=grounding
            + [
                AssistantGroundingItem(
                    kind="suggested_correction",
                    title=finding.title,
                    detail=f"Suggestion: {finding.suggested_correction or 'No automatic correction stored.'}",
                    source_reference=finding.source_reference,
                )
                for finding in corrections[:3]
            ],
            actions=_base_actions(document),
        )

    if any(word in lowered for word in ("approve", "approved", "decision", "sign off", "sign-off")):
        decisions = (
            db.query(ApprovalDecision)
            .filter(ApprovalDecision.document_id == document.id)
            .order_by(ApprovalDecision.created_at.desc())
            .all()
        )
        if not decisions:
            reply = (
                f"No approval decision has been recorded for “{document.title}”. "
                f"The current version is {document.current_version_number} and the latest check scored "
                f"{run.overall_score}/100 with {run.total_findings} finding(s)."
            )
        else:
            lines = [
                f"• Version {decision.decision_metadata.get('version_number', '?')}: "
                f"{decision.decision.replace('_', ' ')} by {decision.reviewer_name} on "
                f"{decision.created_at.strftime('%d %b %Y, %H:%M')}"
                + (f" — “{decision.feedback}”" if decision.feedback else "")
                for decision in decisions[:5]
            ]
            stale = bool(
                document.approved_version_id
                and document.approved_version_id != version.id
            )
            reply = (
                f"Recorded decisions for “{document.title}”:\n"
                + "\n".join(lines)
                + (
                    "\nThe latest version is newer than the approved version, so the approval is stale. "
                    "A reviewer must approve the current version before it can be treated as approved."
                    if stale
                    else ""
                )
            )
        return _result(
            reply=reply,
            verification="verified_from_workspace_records",
            verification_note="Approval records were read from the version-bound decision history.",
            grounding=grounding,
            actions=_base_actions(document),
        )

    if any(word in lowered for word in ("score", "risk", "why", "ready")):
        factors = run.risk_factors or []
        factor_lines = [
            f"• {factor.get('label', factor.get('category'))} ({factor.get('severity')}): "
            f"{factor.get('count')} item(s), −{factor.get('deduction')} points"
            for factor in factors
        ]
        reply = (
            f"The latest check for “{document.title}” scored {run.overall_score}/100 with a "
            f"{run.risk_level} risk level. {run.score_method or ''}\n\n"
            + ("Score breakdown:\n" + "\n".join(factor_lines) if factor_lines else "No deductions were applied.")
        )
        if findings:
            reply += "\n\nHighest-priority open items:\n" + "\n".join(
                _finding_line(f) for f in findings[:3]
            )
        return _result(
            reply=reply,
            verification="verified_from_workspace_records",
            verification_note=(
                "Score, factors, and findings were read from the stored audit run. "
                "The score is a workflow aid, not a legal risk rating."
            ),
            grounding=grounding,
            actions=_base_actions(document),
        )

    if any(word in lowered for word in ("status", "state", "where")):
        decision = (
            db.query(ApprovalDecision)
            .filter(ApprovalDecision.document_id == document.id)
            .order_by(ApprovalDecision.created_at.desc())
            .first()
        )
        reply = (
            f"“{document.title}” is currently **{document.status.replace('_', ' ')}** on version "
            f"{document.current_version_number}. The latest check scored {run.overall_score}/100 and "
            f"found {run.total_findings} item(s)."
        )
        if document.submitted_at:
            reply += f" It was submitted for review on {document.submitted_at.strftime('%d %b %Y, %H:%M')}."
        if content_service.approval_is_stale(document, version):
            reply += " The recorded approval applies to an older version and is now stale."
        if decision:
            reply += (
                f" The most recent decision was “{decision.decision.replace('_', ' ')}” from "
                f"{decision.reviewer_name}."
            )
        return _result(
            reply=reply,
            verification="verified_from_workspace_records",
            verification_note="Document status, version, and approval records came from the workspace database.",
            grounding=grounding,
            actions=_base_actions(document),
        )

    if findings:
        top = findings[:5]
        reply = (
            f"“{document.title}” has {run.total_findings} finding(s) on the current version "
            f"(readiness {run.overall_score}/100, {run.risk_level} risk).\n\n"
            + "\n".join(_finding_line(f) for f in top)
        )
        if len(findings) > len(top):
            reply += f"\n\n…and {len(findings) - len(top)} more in the content workspace."
        return _result(
            reply=reply,
            verification="verified_from_workspace_records",
            verification_note=(
                "Each item above is stored against this audit run. Confirmed contradictions cite the "
                "matching approved fact; uncertain items are explicitly marked for human review."
            ),
            grounding=grounding + [
                AssistantGroundingItem(
                    kind="audit_finding",
                    title=f.title,
                    detail=f.affected_text,
                    source_reference=f.source_reference,
                )
                for f in top[:3]
            ],
            actions=_base_actions(document),
        )

    return _result(
        reply=(
            f"The latest check for “{document.title}” found no issues and scored {run.overall_score}/100. "
            "Keep in mind that automated checks only cover the rules and approved facts stored in this "
            "workspace; they are not a legal review."
        ),
        verification="verified_from_workspace_records",
        verification_note="The audit run and its empty finding set were read from the database.",
        grounding=grounding,
        actions=_base_actions(document),
    )


def _answer_fact_question(
    db: Session, actor: Actor, message: str
) -> Optional[AssistantChatResponse]:
    keywords = _keywords(message)
    facts = (
        db.query(ApprovedFact)
        .filter(ApprovedFact.workspace_id == actor.workspace_id, ApprovedFact.is_active.is_(True))
        .all()
    )
    if not facts:
        return None

    def score_fact(fact: ApprovedFact) -> int:
        haystack = f"{fact.category} {fact.claim_statement} {fact.approved_value} {fact.product or ''}".lower()
        return sum(1 for keyword in keywords if keyword in haystack)

    ranked = sorted(facts, key=score_fact, reverse=True)
    matches = [fact for fact in ranked if score_fact(fact) > 0][:4]
    asks_for_facts = any(
        word in message.lower() for word in ("sla", "uptime", "price", "pricing", "fact", "claim", "approved", "compliance", "savings", "benchmark")
    )
    if not matches:
        if not asks_for_facts:
            return None
        return _result(
            reply=(
                "No approved fact in this workspace matches that question. I cannot verify it from "
                "current records, so I will not guess. An organization administrator can add a sourced "
                "fact in Brand Library → Approved facts."
            ),
            verification="unable_to_verify",
            verification_note="No matching active approved fact was found in the workspace database.",
            actions=[
                AssistantActionSuggestion(
                    action_type="navigate", label="Open approved facts", route="/brand?tab=facts"
                )
            ],
        )

    lines = [
        f"• **{fact.claim_statement}** — “{fact.approved_value}” "
        f"(source: {fact.source_reference}; status: {fact.status})"
        for fact in matches
    ]
    return _result(
        reply="Here is what the workspace records approve:\n\n" + "\n".join(lines),
        verification="verified_from_workspace_records",
        verification_note=(
            "The answer quotes active approved facts exactly. It does not extend or reinterpret them. "
            "Facts marked needs review or expired should be treated as stale."
        ),
        grounding=[
            AssistantGroundingItem(
                kind="approved_fact",
                title=fact.claim_statement,
                detail=fact.approved_value,
                source_reference=fact.source_reference,
            )
            for fact in matches
        ],
        actions=[
            AssistantActionSuggestion(
                action_type="navigate", label="Open approved facts", route="/brand?tab=facts"
            )
        ],
    )


def _answer_rule_question(db: Session, actor: Actor, message: str) -> Optional[AssistantChatResponse]:
    lowered = message.lower()
    if not any(word in lowered for word in ("rule", "policy", "policies", "prohibited", "banned", "tone", "terminology")):
        return None
    rules = (
        db.query(BrandRule)
        .filter(BrandRule.workspace_id == actor.workspace_id)
        .order_by(BrandRule.is_active.desc(), BrandRule.name)
        .all()
    )
    active = [rule for rule in rules if rule.is_active and (rule.status or "active") == "active"]
    if not active:
        return _result(
            reply="No active brand rules are stored in this workspace, so no policy checks are being applied.",
            verification="verified_from_workspace_records",
            verification_note="The brand rule table was queried for this workspace.",
        )
    lines = [
        f"• **{rule.name}** ({rule.severity}) — {rule.rule_type.replace('_', ' ')}. "
        f"Pattern: “{rule.pattern_or_phrase}”."
        + (f" Guidance: “{rule.replacement_or_guidance}”." if rule.replacement_or_guidance else "")
        for rule in active
    ]
    return _result(
        reply=(
            f"This workspace has {len(active)} active brand rule(s):\n\n" + "\n".join(lines)
        ),
        verification="verified_from_workspace_records",
        verification_note="Each rule was read from the Brand Library; draft and archived rules are excluded from checks.",
        grounding=[
            AssistantGroundingItem(
                kind="brand_rule",
                title=rule.name,
                detail=f"{rule.rule_type} · severity {rule.severity} · pattern “{rule.pattern_or_phrase}”",
                source_reference=f"Brand policy v{rule.version}",
            )
            for rule in active[:5]
        ],
        actions=[
            AssistantActionSuggestion(
                action_type="navigate", label="Open brand rules", route="/brand?tab=rules"
            )
        ],
    )


def _answer_campaign(
    db: Session, actor: Actor, request: AssistantChatRequest
) -> Optional[AssistantChatResponse]:
    if not request.campaign_id:
        return None
    campaign = (
        db.query(Campaign)
        .filter(Campaign.id == request.campaign_id, Campaign.workspace_id == actor.workspace_id)
        .first()
    )
    if not campaign:
        raise HTTPException(status_code=404, detail="The referenced campaign was not found.")
    conflicts = (
        db.query(CampaignConflict)
        .filter(CampaignConflict.campaign_id == campaign.id)
        .all()
    )
    readiness = build_readiness(db, campaign, conflicts)
    unresolved = [c for c in conflicts if c.status == "unresolved"]
    reply = (
        f"**{campaign.name}** currently has {len(campaign.documents)} asset(s) and "
        f"{len(unresolved)} unresolved cross-asset conflict(s). Campaign readiness is "
        f"“{readiness['result'].replace('_', ' ')}”: {readiness['summary']}"
    )
    if unresolved:
        reply += "\n\nUnresolved conflicts:\n" + "\n".join(
            f"• {conflict.topic}: “{conflict.asset_a_value}” ({conflict.asset_a_title}) vs "
            f"“{conflict.asset_b_value}” ({conflict.asset_b_title})"
            for conflict in unresolved[:4]
        )
    return _result(
        reply=reply,
        verification="verified_from_workspace_records",
        verification_note=(
            "Assets, conflicts, and readiness checks were read from the campaign database. "
            "Readiness is an internal consistency check, not a legal launch approval."
        ),
        grounding=[
            AssistantGroundingItem(
                kind="campaign_conflict",
                title=conflict.topic,
                detail=(
                    f"{conflict.asset_a_title}: {conflict.asset_a_value}; "
                    f"{conflict.asset_b_title}: {conflict.asset_b_value}"
                ),
                source_reference=conflict.evidence_note,
            )
            for conflict in unresolved[:5]
        ],
        actions=[
            AssistantActionSuggestion(
                action_type="open_campaign",
                label=f"Open {campaign.name}",
                route=f"/campaigns/{campaign.id}",
                target_id=campaign.id,
            )
        ],
    )


def _answer_review_queue(db: Session, actor: Actor) -> Optional[AssistantChatResponse]:
    if not actor.can("review.queue"):
        own = (
            db.query(ContentDocument)
            .filter(
                ContentDocument.workspace_id == actor.workspace_id,
                ContentDocument.created_by == actor.id,
                ContentDocument.status.in_(["in_review", "changes_requested"]),
            )
            .order_by(ContentDocument.submitted_at.asc())
            .all()
        )
        if not own:
            reply = (
                "The review queue is available to reviewers and admins. You have no submissions "
                "currently waiting for a decision."
            )
        else:
            lines = [
                f"• “{document.title}” — v{document.current_version_number}, "
                f"{document.status.replace('_', ' ')}"
                for document in own[:6]
            ]
            reply = (
                "The shared review queue is available to reviewers and admins. Your own submissions "
                f"currently waiting on a decision ({len(own)}):\n\n" + "\n".join(lines)
            )
        return _result(
            reply=reply,
            verification="verified_from_workspace_records",
            verification_note=(
                "Your role cannot review other people's content; these items were filtered to "
                "submissions you created in this workspace."
            ),
            actions=[
                AssistantActionSuggestion(action_type="navigate", label="Open your content", route="/content")
            ],
        )
    documents = (
        db.query(ContentDocument)
        .filter(
            ContentDocument.workspace_id == actor.workspace_id,
            ContentDocument.status.in_(["in_review", "changes_requested"]),
        )
        .order_by(ContentDocument.submitted_at.asc())
        .all()
    )
    if not documents:
        return _result(
            reply="The review queue is empty right now. No content is waiting for a reviewer decision.",
            verification="verified_from_workspace_records",
            verification_note="The content table was queried for items in review or changes requested.",
            actions=[
                AssistantActionSuggestion(action_type="navigate", label="Open review queue", route="/reviews")
            ],
        )
    lines = [
        f"• “{doc.title}” — v{doc.current_version_number}, {doc.status.replace('_', ' ')}"
        + (f", submitted by {doc.submitted_by_name}" if doc.submitted_by_name else "")
        for doc in documents[:6]
    ]
    return _result(
        reply=f"There are {len(documents)} item(s) waiting for review:\n\n" + "\n".join(lines),
        verification="verified_from_workspace_records",
        verification_note="Queue items and statuses were read from the workspace database.",
        actions=[
            AssistantActionSuggestion(action_type="navigate", label="Open review queue", route="/reviews")
        ],
    )


def _answer_attention(db: Session, actor: Actor) -> AssistantChatResponse:
    priorities: list[dict] = []
    high_open_total = 0
    for document in _accessible_documents(db, actor):
        version, run = _latest_audit(db, document)
        high_open = 0
        if run:
            high_open = (
                db.query(func.count(AuditFinding.id))
                .filter(
                    AuditFinding.audit_run_id == run.id,
                    AuditFinding.status == "open",
                    AuditFinding.severity.in_(["high", "critical"]),
                )
                .scalar()
            ) or 0
            high_open_total += high_open
        if document.status == "changes_requested":
            priorities.append(
                {
                    "rank": 0,
                    "title": document.title,
                    "detail": (
                        f"Changes were requested on version {document.current_version_number}. "
                        "Open the notes, revise, and resubmit."
                    ),
                    "route": f"/content/{document.id}",
                }
            )
        elif actor.can("review.queue") and document.status == "in_review":
            priorities.append(
                {
                    "rank": 0,
                    "title": document.title,
                    "detail": (
                        f"Version {document.current_version_number} is waiting for a reviewer decision."
                    ),
                    "route": f"/content/{document.id}",
                }
            )
        elif run and high_open:
            priorities.append(
                {
                    "rank": 0,
                    "title": document.title,
                    "detail": (
                        f"The latest check has {high_open} open high/critical finding(s) "
                        f"(readiness {run.overall_score}/100)."
                    ),
                    "route": f"/content/{document.id}",
                }
            )
        elif run and run.overall_score < 80 and document.status != "approved":
            priorities.append(
                {
                    "rank": 1,
                    "title": document.title,
                    "detail": (
                        f"The latest check scored {run.overall_score}/100 with "
                        f"{run.total_findings} finding(s)."
                    ),
                    "route": f"/content/{document.id}",
                }
            )

    unresolved = (
        db.query(func.count(CampaignConflict.id))
        .join(Campaign, Campaign.id == CampaignConflict.campaign_id)
        .filter(
            Campaign.workspace_id == actor.workspace_id,
            CampaignConflict.status == "unresolved",
        )
        .scalar()
    ) or 0
    if unresolved:
        priorities.append(
            {
                "rank": 0,
                "title": f"{unresolved} unresolved campaign conflict{'s' if unresolved != 1 else ''}",
                "detail": "Campaign assets make inconsistent claims; resolve values before launch.",
                "route": "/campaigns",
            }
        )

    priorities.sort(key=lambda item: item["rank"])
    top = priorities[:5]
    pending_own = sum(
        1
        for document in _accessible_documents(db, actor)
        if document.status in {"in_review", "changes_requested"}
    )
    if not top:
        return _result(
            reply=(
                "Nothing in the content you can access is currently flagged: no change requests, "
                "no open high/critical findings, and no unresolved campaign conflicts. "
                f"{pending_own} item(s) of yours are still waiting on a review decision."
                if pending_own
                else "Nothing in the content you can access is currently flagged: no change requests, "
                "no open high/critical findings, and no unresolved campaign conflicts."
            ),
            verification="verified_from_workspace_records",
            verification_note=(
                "The assistant checked accessible documents, their latest audit runs, and campaign "
                "conflicts. Scores are workflow aids, not legal risk ratings."
            ),
            actions=[
                AssistantActionSuggestion(action_type="navigate", label="Open content", route="/content")
            ],
        )

    lines = [f"• **{item['title']}** — {item['detail']}" for item in top]
    actions: list[AssistantActionSuggestion] = []
    seen_routes: set[str] = set()
    for item in top:
        if item["route"] in seen_routes or len(actions) >= 3:
            continue
        seen_routes.add(item["route"])
        actions.append(
            AssistantActionSuggestion(
                action_type="navigate",
                label=f"Open {item['title']}",
                route=item["route"],
            )
        )
    return _result(
        reply=(
            "Here is what needs attention in this workspace right now:\n\n"
            + "\n".join(lines)
            + f"\n\n{high_open_total} open high/critical finding(s) across the latest checks you can access."
        ),
        verification="verified_from_workspace_records",
        verification_note=(
            "Priorities were computed from accessible documents, review statuses, latest audit runs, "
            "and unresolved campaign conflicts. Scores are workflow aids, not legal risk ratings."
        ),
        grounding=[
            AssistantGroundingItem(
                kind="record",
                title=item["title"],
                detail=item["detail"],
                source_reference="Workspace priority check",
            )
            for item in top[:4]
        ],
        actions=actions,
    )


def _answer_outdated_facts(db: Session, actor: Actor, message: str) -> Optional[AssistantChatResponse]:
    lowered = message.lower()
    if "fact" not in lowered:
        return None
    if not any(
        word in lowered
        for word in ("outdated", "stale", "expired", "needs review", "need review", "review due", "old")
    ):
        return None
    if not actor.can("brand.read"):
        return _result(
            reply="Your role cannot read the approved-facts register, so I cannot check fact freshness.",
            verification="unable_to_verify",
            verification_note="The assistant respects the brand.read capability.",
        )
    facts = (
        db.query(ApprovedFact)
        .filter(ApprovedFact.workspace_id == actor.workspace_id, ApprovedFact.is_active.is_(True))
        .all()
    )
    now = datetime.now(timezone.utc)
    stale: list[tuple[ApprovedFact, Optional[datetime]]] = []
    for fact in facts:
        next_review = fact.next_review_at
        if next_review and next_review.tzinfo is None:
            next_review = next_review.replace(tzinfo=timezone.utc)
        if fact.status in {"expired", "needs_review"} or (next_review and next_review < now):
            stale.append((fact, next_review))
    if not stale:
        return _result(
            reply=(
                f"No active approved fact is outdated right now. None of the {len(facts)} active "
                "fact(s) is marked expired or needs review, and none is past its scheduled review date."
            ),
            verification="verified_from_workspace_records",
            verification_note="Active approved facts and next-review dates were read from the workspace database.",
            actions=[
                AssistantActionSuggestion(
                    action_type="navigate", label="Open approved facts", route="/brand?tab=facts"
                )
            ],
        )
    lines = []
    for fact, next_review in stale[:5]:
        due = (
            f"; review was due {next_review.strftime('%d %b %Y')}"
            if next_review and next_review < now
            else ""
        )
        lines.append(
            f"• **{fact.claim_statement}** — status {fact.status.replace('_', ' ')}{due}. "
            f"Approved value: “{fact.approved_value}”."
        )
    return _result(
        reply=(
            f"{len(stale)} active approved fact(s) are outdated or due for review:\n\n"
            + "\n".join(lines)
            + "\n\nTreat these as stale when checking content; an administrator can update or retire "
            "them in Brand Library → Approved facts."
        ),
        verification="verified_from_workspace_records",
        verification_note=(
            "Statuses and next-review dates were read from the approved-fact register for this workspace."
        ),
        grounding=[
            AssistantGroundingItem(
                kind="approved_fact",
                title=fact.claim_statement,
                detail=f"{fact.approved_value} · status {fact.status}",
                source_reference=fact.source_reference,
            )
            for fact, _ in stale[:5]
        ],
        actions=[
            AssistantActionSuggestion(
                action_type="navigate", label="Open approved facts", route="/brand?tab=facts"
            )
        ],
    )


