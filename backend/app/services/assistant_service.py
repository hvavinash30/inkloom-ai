def _answer_rule_based(
    db: Session, actor: Actor, request: AssistantChatRequest
) -> AssistantChatResponse:
    message = request.message.strip()
    lowered = message.lower()

    if request.finding_id:
        finding = db.query(AuditFinding).filter(AuditFinding.id == request.finding_id).first()
        if not finding:
            raise HTTPException(status_code=404, detail="The referenced finding was not found.")
        document = _focused_document(db, actor, finding.audit_run.document_id)
        lowered = message.lower()
        finding_terms = (
            "finding",
            "evidence",
            "source",
            "quote",
            "why",
            "explain",
            "severity",
            "risk",
            "confirmed",
            "contradiction",
            "correction",
            "correct",
            "fix",
            "revise",
            "revision",
            "rewrite",
            "change",
            "location",
            "page",
        )
        if not any(term in lowered for term in finding_terms):
            # Keep the finding attached, but let follow-up questions use the document's records.
            return _answer_for_document(db, actor, document, message)

        wants_correction = bool(
            re.search(r"\b(fix|fixes|correct|correction|corrections|revise|revision|rewrite|change)\b", lowered)
        )
        reply = (
            f"Finding “{finding.title}” ({finding.severity}) in “{document.title}” at "
            f"{finding.location_label or 'the document'}.\n\n"
            f"Affected text: “{finding.affected_text}”\n\n{finding.explanation}"
            + (f"\n\nSource: {finding.source_reference}." if finding.source_reference else "")
        )
        if wants_correction:
            reply += (
                f"\n\nSuggested revision (not applied): “{finding.suggested_correction}”. "
                "The original document has not been changed."
                if finding.suggested_correction
                else "\n\nNo automatic correction is stored for this finding; a human editor should decide."
            )
        elif finding.suggested_correction:
            reply += f"\nSuggested correction: “{finding.suggested_correction}”."
        else:
            reply += "\nNo automatic correction is available."
        return _result(
            reply=reply,
            verification="verified_from_workspace_records",
            verification_note="This is a direct quote of the stored finding and its evidence.",
            grounding=[
                AssistantGroundingItem(
                    kind="audit_finding",
                    title=finding.title,
                    detail=finding.affected_text,
                    source_reference=finding.source_reference,
                )
            ],
            actions=_base_actions(document),
        )

    if request.document_id:
        document = _focused_document(db, actor, request.document_id)
        return _answer_for_document(db, actor, document, message)

    campaign_answer = _answer_campaign(db, actor, request)
    if campaign_answer:
        return campaign_answer

    if any(
        phrase in lowered
        for phrase in (
            "needs my attention",
            "needs attention",
            "attention today",
            "what should i work on",
            "what should i do",
            "what is urgent",
            "what's urgent",
            "my priorities",
            "prioritize",
        )
    ):
        return _answer_attention(db, actor)

    if any(
        phrase in lowered
        for phrase in ("review queue", "pending review", "waiting for review", "what needs review")
    ):
        queue_answer = _answer_review_queue(db, actor)
        if queue_answer:
            return queue_answer

    outdated_answer = _answer_outdated_facts(db, actor, message)
    if outdated_answer:
        return outdated_answer

    insights_answer = _answer_governance_insights(db, actor, message)
    if insights_answer:
        return insights_answer

    process_answer = _answer_review_process(actor, message)
    if process_answer:
        return process_answer

    if any(
        phrase in lowered
        for phrase in (
            "score mean",
            "does the score",
            "does an audit score",
            "audit score mean",
            "readiness score mean",
            "how is the score",
            "how are scores",
            "score calculated",
            "explain the score",
        )
    ):
        return _answer_score_meaning()

    fact_answer = _answer_fact_question(db, actor, message)
    if fact_answer:
        return fact_answer

    rule_answer = _answer_rule_question(db, actor, message)
    if rule_answer:
        return rule_answer

    if any(
        phrase in lowered
        for phrase in ("summary", "overview", "how are we doing", "workspace status", "status report")
    ):
        return _answer_workspace_summary(db, actor)

    if any(word in lowered for word in ("help", "what can you do", "capabilities")):
        return _result(
            reply=(
                "I can answer questions from this workspace's records: approved facts (SLA, pricing, "
                "benchmarks, compliance), active brand rules, audit findings and scores, review "
                "decisions, and campaign conflicts. Try asking:\n"
                "• “What SLA is approved?”\n"
                "• “Why did this content score low?” (open a content item first)\n"
                "• “What is waiting in the review queue?”\n"
                "• “Which rules are active?”"
            ),
            verification="general_guidance",
            verification_note=(
                "This is built-in product guidance, not a fact retrieved from workspace records."
            ),
        )

    if any(word in lowered for word in ("content", "document", "copy", "draft")):
        return _answer_workspace_summary(db, actor)

    return _result(
        reply=(
            "I could not verify that request from the workspace records, so I will not invent an answer. "
            "Ask me about approved facts, brand rules, a specific content item, the review queue, or a "
            "campaign. You can open a document and use the assistant there for finding-specific questions."
        ),
        verification="unable_to_verify",
        verification_note=(
            "No matching approved fact, rule, document, or campaign record was found for the question."
        ),
        limitations=[
            "The assistant does not browse the web.",
            _assistant_engine_note(),
            "It deliberately declines questions it cannot ground in workspace records.",
        ],
    )


ASSISTANT_LLM_SYSTEM = """You are the Inkloom brand-governance assistant. You will receive a user
question and a record-grounded answer produced by Inkloom's deterministic guide. Rewrite that answer
so it reads clearly and directly addresses the question.

Hard rules:
- Use only facts, numbers, names, statuses, and quotes present in the supplied grounded answer.
- Never add documents, findings, policies, URLs, recommendations, or numbers that are not supplied.
- Preserve every quoted string, suggested correction, route, and verification caveat verbatim.
- Do not claim an action was taken, approved, published, or saved.
- Do not present the readiness score as a legal risk rating.
- If the grounded answer says something could not be verified, keep that limitation.
- 180 words maximum. Plain text only, no markdown headings.

Return a single JSON object: {"reply": "..."}"""


def _llm_prompt(message: str, response: AssistantChatResponse) -> str:
    grounding_lines = [
        f"- {item.kind}: {item.title} — {item.detail}"
        + (f" (source: {item.source_reference})" if item.source_reference else "")
        for item in response.grounding[:8]
    ]
    action_lines = [f"- {action.label}" for action in response.suggested_actions[:6]]
    return (
        f"User question:\n{message[:1500]}\n\n"
        f"Verification status: {response.verification}\n"
        f"Verification note: {response.verification_note}\n\n"
        f"Grounded answer to rewrite:\n{response.reply}\n\n"
        "Grounding records:\n"
        + ("\n".join(grounding_lines) if grounding_lines else "- None listed")
        + "\n\nAvailable actions:\n"
        + ("\n".join(action_lines) if action_lines else "- None")
    )


def _llm_failure(response: AssistantChatResponse, message: str, error_kind: str = "") -> AssistantChatResponse:
    diagnostic = dict(response.diagnostic_info or {})
    diagnostic["ai"] = {
        "attempted": True,
        "provider": ai_provider.active_provider(),
        "error_kind": error_kind or "unavailable",
    }
    return AssistantChatResponse(
        reply=response.reply,
        mode="rule_based",
        verification=response.verification,
        verification_note=response.verification_note,
        grounding=response.grounding,
        suggested_actions=response.suggested_actions,
        limitations=[
            *response.limitations,
            "The configured AI provider could not refine this answer, so the record-grounded text is shown unchanged.",
        ],
        diagnostic_info=diagnostic,
        provider=ai_provider.active_provider(),
        ai_error=message,
    )


def _maybe_llm(
    actor: Actor, message: str, response: AssistantChatResponse
) -> AssistantChatResponse:
    if (
        not settings.llm_configured
        or response.mode != "rule_based"
        or response.verification == "unable_to_verify"
    ):
        return response
    if not ai_provider.allow_request(f"assistant:{actor.id}"):
        return _llm_failure(
            response,
            "The AI rate limit for this account was reached. The record-grounded answer is shown; try again shortly.",
            error_kind="rate_limited",
        )

    ai_response, parsed = ai_provider.complete_json(
        ASSISTANT_LLM_SYSTEM,
        _llm_prompt(message, response),
        ("reply",),
    )
    if not ai_response.ok or parsed is None:
        return _llm_failure(
            response,
            ai_response.error_message or "The configured AI provider is unavailable right now.",
            error_kind=ai_response.error_kind,
        )
    reply = str(parsed.get("reply") or "").strip()
    if not reply:
        return _llm_failure(
            response,
            "The AI provider returned an empty answer.",
            error_kind="empty_response",
        )
    diagnostic = dict(response.diagnostic_info or {})
    diagnostic["ai"] = {
        "attempted": True,
        "provider": ai_response.provider,
        "model": ai_response.model,
        "error_kind": "",
    }
    return AssistantChatResponse(
        reply=reply[:4000],
        mode="grounded_llm",
        verification=response.verification,
        verification_note=(
            f"{response.verification_note} Wording was generated by the configured "
            f"{ai_response.provider} model strictly from this record-grounded answer."
        ),
        grounding=response.grounding,
        suggested_actions=response.suggested_actions,
        limitations=[
            *response.limitations,
            "AI wording is constrained to the cited record answer; verify any quoted text against its source.",
        ],
        diagnostic_info=diagnostic,
        provider=ai_response.provider,
    )


def answer_query(db: Session, actor: Actor, request: AssistantChatRequest) -> AssistantChatResponse:
    return _maybe_llm(actor, request.message.strip(), _answer_rule_based(db, actor, request))
